func TestTickSkipsWhatIsNotLearned(t *testing.T) {
	home := t.TempDir()
	good := runs([]string{"a", "b", "c"}, 2, true)
	// Hand-written, library and imported skills, and one the owner quarantined.
	writeTestSkill(t, home, "hand-written", "validated", omap{})
	writeTestSkill(t, home, "from-library", "validated", omap{{"auto_generated", true}, {"source", "library"}})
	writeTestSkill(t, home, "library-id", "validated", omap{{"lifecycle", "probation"}, {"library_id", "x/y"}})
	writeTestSkill(t, home, "imported", "validated", omap{{"auto_generated", true}, {"trust", "imported"}})
	writeTestSkill(t, home, "quarantined", "disabled", omap{{"auto_generated", true}, {"quarantine", "true"},
		{"manual_override", "quarantine"}})
	// Lifecycle-managed (a manual promote) counts as learned.
	writeTestSkill(t, home, "managed", "validated", omap{{"lifecycle", "manual-promote"}})
	writeStats(t, home, map[string][]run{"hand-written": good, "from-library": good, "library-id": good,
		"imported": good, "quarantined": good, "managed": good})
	changes, err := TickLearnedSkills(home, lcNow, 0)
	if err != nil {
		t.Fatal(err)
	}
	if len(changes) != 1 || changes[0].Name != "managed" {
		t.Fatalf("changes=%+v", changes)
	}
	for _, n := range []string{"hand-written", "from-library", "library-id", "imported"} {
		if s := statusOf(t, home, n); s.status != "validated" {
			t.Errorf("%s changed to %s", n, s.status)
		}
	}
	if s := statusOf(t, home, "quarantined"); s.status != "disabled" {
		t.Errorf("a quarantined skill was re-promoted to %s", s.status)
	}
}


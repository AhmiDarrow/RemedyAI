func writeTestSkill(t *testing.T, home, name, status string, meta omap) string {
	t.Helper()
	s := &skill{name: name, description: "Test skill description long enough for validation",
		version: "0.1.0", status: status, meta: meta,
		instructions: "# steps\n" + strings.Repeat("do the thing\n", 12)}
	path, err := writeSkill(filepath.Join(home, "skills"), s)
	if err != nil {
		t.Fatal(err)
	}
	return path
}

func learnedMeta(effort float64) omap {
	return omap{{"auto_generated", true}, {"effort_weight", effort}, {"lifecycle", "probation"},
		{"created_at", isoNow(lcNow.AddDate(0, 0, -3))}}
}

// writeStats records runs the way SkillRefiner.record_execution does.
func writeStats(t *testing.T, home string, runs map[string][]struct {
	session string
	ok      bool
}) {
	t.Helper()
	skills := map[string]any{}
	for name, rs := range runs {
		row := map[string]any{}
		for _, r := range rs {
			recordExecution(row, r.ok, r.session, "", isoNow(lcNow.Add(-time.Hour)))
		}
		skills[name] = row
	}
	raw, _ := json.MarshalIndent(map[string]any{"version": 1, "skills": skills}, "", "  ")
	if err := os.WriteFile(filepath.Join(home, "skill_stats.json"), raw, 0o600); err != nil {
		t.Fatal(err)
	}
}

type run = struct {
	session string
	ok      bool
}

func runs(sessions []string, per int, ok bool) []run {
	var out []run
	for _, s := range sessions {
		for i := 0; i < per; i++ {
			out = append(out, run{s, ok})
		}
	}
	return out
}

func statusOf(t *testing.T, home, name string) *skill {
	t.Helper()
	s, err := readSkill(filepath.Join(home, "skills", name))
	if err != nil {
		t.Fatal(err)
	}
	return s
}

// test_tick_learned_skills_promotes_without_user.
func TestTickPromotesWithoutUser(t *testing.T) {
	home := t.TempDir()
	writeTestSkill(t, home, "tick-promote", "validated", learnedMeta(0.2))
	writeStats(t, home, map[string][]run{"tick-promote": runs([]string{"a", "b", "c"}, 2, true)})
	changes, err := TickLearnedSkills(home, lcNow, 0)
	if err != nil {
		t.Fatal(err)
	}
	if len(changes) != 1 || changes[0].Name != "tick-promote" || changes[0].Action != "promote" ||
		changes[0].From != "validated" || changes[0].To != "active" {
		t.Fatalf("changes=%+v", changes)
	}
	s := statusOf(t, home, "tick-promote")
	if s.status != "active" {
		t.Fatalf("status=%s", s.status)
	}
	for k, want := range map[string]any{"lifecycle_action": "promote", "success_rate": 1.0,
		"total_executions": 6, "stats_sessions": 3, "lifecycle_changed_at": isoNow(lcNow)} {
		if got, _ := s.meta.get(k); got != want {
			t.Errorf("meta %s = %#v, want %#v", k, got, want)
		}
	}
	if last, _ := s.meta.get("lifecycle_last"); !strings.Contains(scalarText(last), "promote to ACTIVE") {
		t.Errorf("lifecycle_last=%v", last)
	}
	// Nothing left to do: a second tick changes nothing.
	if again, err := TickLearnedSkills(home, lcNow, 0); err != nil || len(again) != 0 {
		t.Fatalf("second tick: %+v %v", again, err)
	}
}


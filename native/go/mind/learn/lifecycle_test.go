// Cases from tests/test_skill_lifecycle.py and tests/test_learning_loop_hard.py.

var lcNow = time.Date(2026, 11, 27, 12, 0, 0, 0, time.UTC)

func ptime(t time.Time) *time.Time { return &t }

func TestEvaluateHealthCases(t *testing.T) {
	cases := []struct {
		name       string
		h          health
		action, to string
		reason     string
	}{
		{"hard-won resists prune", health{name: "hard-skill", status: "disabled", total: 4, failures: 4, sessions: 2,
			effort: 0.9, autoGenerated: true, lastFailure: ptime(lcNow)}, "hold", "disabled", ""},
		{"easy skill prunes faster", health{name: "easy-skill", status: "discovered", total: 3, failures: 3, sessions: 1,
			effort: 0.1, autoGenerated: true}, "prune", "deprecated", "3 runs with zero successes"},
		{"hard-won streak of 3 holds", health{name: "hw", status: "active", total: 10, successes: 7, failures: 3,
			sessions: 3, streak: 3, effort: 0.85}, "hold", "active", "keep active (n=10, rate=70%, effort=0.85)"},
		{"hard-won streak of 6 demotes", health{name: "hw", status: "active", total: 10, successes: 4, failures: 6,
			sessions: 3, streak: 6, effort: 0.85}, "demote", "disabled", "6 consecutive failures (threshold 6"},
		{"stale unused auto skill demotes", health{name: "u", status: "discovered", autoGenerated: true,
			createdAt: ptime(lcNow.AddDate(0, 0, -(staleUnusedDays + 1)))}, "demote", "disabled", "never used in 22d"},
		{"recently created unused holds", health{name: "u", status: "discovered", autoGenerated: true,
			createdAt: ptime(lcNow.AddDate(0, 0, -2))}, "hold", "discovered", ""},
		{"activated unused is not stale", health{name: "u", status: "validated", autoGenerated: true, activations: 1,
			createdAt: ptime(lcNow.AddDate(0, 0, -60))}, "hold", "validated", ""},
		{"no creation date holds", health{name: "u", status: "discovered", autoGenerated: true}, "hold", "discovered", ""},
		{"stale disabled prunes via status change", health{name: "u", status: "disabled", autoGenerated: true,
			createdAt:       ptime(lcNow.AddDate(0, 0, -90)),
			statusChangedAt: ptime(lcNow.AddDate(0, 0, -(pruneDisabledDays + 1)))}, "prune", "deprecated", "disabled and stale (31d)"},
		{"freshly disabled is not pruned", health{name: "u", status: "disabled", autoGenerated: true,
			createdAt: ptime(lcNow.AddDate(0, 0, -90)), statusChangedAt: ptime(lcNow)}, "hold", "disabled", ""},
		{"one success never promotes discovered", health{name: "once", status: "discovered", total: 1, successes: 1,
			sessions: 1, effort: 0.1}, "hold", "discovered", ""},
		{"single session cannot reach active", health{name: "one", status: "validated", total: 5, successes: 5,
			sessions: 1, effort: 0.1}, "hold", "validated", ""},
		{"multi-session promotes active", health{name: "multi", status: "validated", total: 6, successes: 6,
			sessions: 3, effort: 0.2}, "promote", "active", "promote to ACTIVE (n=6, rate=100%, sessions=3, effort=0.20)"},
		{"probation passes to validated", health{name: "p", status: "discovered", total: 3, successes: 3,
			sessions: 1, effort: 0.1}, "promote", "validated", "probation passed → VALIDATED (effort=0.10)"},
		{"hard-won probation needs two", health{name: "p", status: "discovered", total: 2, successes: 2,
			sessions: 1, effort: 0.7}, "promote", "validated", ""},
		{"unreliable active demotes", health{name: "bad", status: "active", total: 9, successes: 3, failures: 6,
			sessions: 2, effort: 0.1}, "demote", "disabled", "demote to DISABLED (n=9, rate=33%, effort=0.10)"},
		{"three failures demote validated", health{name: "shaky", status: "validated", total: 3, failures: 3,
			streak: 3, autoGenerated: true}, "demote", "disabled", "3 consecutive failures"},
		{"hard-won disabled with successes held", health{name: "h", status: "disabled", total: 4, successes: 1, failures: 3,
			effort: 0.8, lastFailure: ptime(lcNow.AddDate(0, 0, -100))}, "hold", "disabled", "held for revive window"},
	}
	for _, c := range cases {
		d := evaluateHealth(c.h, lcNow)
		if d.action != c.action || d.newStatus != c.to || !strings.Contains(d.reason, c.reason) {
			t.Errorf("%s: got %+v, want %s -> %s (%q)", c.name, d, c.action, c.to, c.reason)
		}
	}
}

func TestParseISO(t *testing.T) {
	for _, s := range []string{"2026-11-27T12:00:00+00:00", "2026-11-27T12:00:00.123456+00:00",
		"2026-11-27T12:00:00Z", "2026-11-27T12:00:00", "2026-11-27T14:00:00+02:00", "2026-11-27 12:00:00"} {
		got, ok := parseISO(s)
		if !ok || !got.Truncate(time.Second).Equal(lcNow) {
			t.Errorf("parseISO(%q) = %v, %v", s, got, ok)
		}
	}
	for _, v := range []any{nil, "", "not a date", 12} {
		if _, ok := parseISO(v); ok {
			t.Errorf("parseISO(%v) parsed", v)
		}
	}
}


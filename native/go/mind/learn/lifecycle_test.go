// test_auto_refine_does_not_resurrect_demoted.
func TestTickDoesNotResurrectDemoted(t *testing.T) {
	home := t.TempDir()
	writeTestSkill(t, home, "demote-me", "active", learnedMeta(0.1))
	writeStats(t, home, map[string][]run{"demote-me": append(runs([]string{"s1"}, 3, true), runs([]string{"s2"}, 6, false)...)})
	if _, err := TickLearnedSkills(home, lcNow, 0); err != nil {
		t.Fatal(err)
	}
	if s := statusOf(t, home, "demote-me"); s.status != "disabled" && s.status != "deprecated" {
		t.Fatalf("status=%s", s.status)
	}
	if _, err := TickLearnedSkills(home, lcNow, 0); err != nil {
		t.Fatal(err)
	}
	if s := statusOf(t, home, "demote-me"); s.status == "active" {
		t.Fatal("a demoted skill bounced back to active")
	}
}

// test_tick_demotes_then_retires_stale_unused_skill.
func TestTickDemotesThenRetiresStaleUnused(t *testing.T) {
	home := t.TempDir()
	meta := omap{{"auto_generated", true}, {"created_at", isoNow(lcNow.AddDate(0, 0, -(staleUnusedDays + 1)))}}
	path := writeTestSkill(t, home, "unused-skill", "discovered", meta)
	changes, err := TickLearnedSkills(home, lcNow, 0)
	if err != nil || len(changes) != 1 || changes[0].To != "disabled" {
		t.Fatalf("changes=%+v err=%v", changes, err)
	}
	s := statusOf(t, home, "unused-skill")
	if v, _ := s.meta.get("lifecycle_changed_at"); scalarText(v) == "" {
		t.Fatal("lifecycle_changed_at not stamped")
	}
	if v, _ := s.meta.get("success_rate"); v != 0.5 {
		t.Fatalf("an unused skill mirrors the refiner's 0.5 rate, got %v", v)
	}
	// Nothing happens until the disabled window elapses...
	if changes, _ := TickLearnedSkills(home, lcNow.AddDate(0, 0, 1), 0); len(changes) != 0 {
		t.Fatalf("pruned too early: %+v", changes)
	}
	// ...then it retires: still on disk, just hidden.
	changes, err = TickLearnedSkills(home, lcNow.AddDate(0, 0, 400), 0)
	if err != nil || len(changes) != 1 || changes[0].Action != "prune" || changes[0].To != "deprecated" {
		t.Fatalf("changes=%+v err=%v", changes, err)
	}
	raw, err := os.ReadFile(path)
	if err != nil || !strings.Contains(string(raw), "status: deprecated") {
		t.Fatalf("SKILL.md=%s err=%v", raw, err)
	}
}


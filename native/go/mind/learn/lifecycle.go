// skillsMu serializes this process's writes to learned SKILL.md files and
// skill_stats.json: two turns can end at once.
var skillsMu sync.Mutex

// Lifecycle thresholds (core/learning/lifecycle.py).
const (
	promoteMinExecutions = 5
	promoteMinRate       = 0.80
	promoteMinSessions   = 2
	demoteMinExecutions  = 5
	demoteMaxRate        = 0.50
	demoteStreak         = 3
	probationMinExec     = 3
	pruneZeroMinN        = 3
	pruneDisabledDays    = 30
	staleUnusedDays      = 21
	tickDefaultLimit     = 64
)

// SkillChange is one status change the lifecycle tick applied.
type SkillChange struct {
	Name   string `json:"name"`
	Action string `json:"action"`
	From   string `json:"from"`
	To     string `json:"to"`
	Reason string `json:"reason"`
}

// skillStats is one row of skill_stats.json, as SkillRefiner.load_stats
// reads it.
type skillStats struct {
	total, successes, failures int64
	sessions                   int
	streak                     int64
	activations                int64
	lastSuccess, lastFailure   *time.Time
}

// successRate is SkillStats.success_rate (0.5 before any run).
func (s skillStats) successRate() float64 {
	if s.total == 0 {
		return 0.5
	}
	return float64(s.successes) / float64(s.total)
}

// loadSkillStats reads <home>/skill_stats.json. A missing file is no stats.
// A file that cannot be parsed is an error: the tick then changes nothing
// rather than judge every skill as never used (Python treated it as empty).
func loadSkillStats(home string) (map[string]skillStats, error) {
	raw, err := os.ReadFile(filepath.Join(home, "skill_stats.json"))
	if errors.Is(err, os.ErrNotExist) {
		return map[string]skillStats{}, nil
	}
	if err != nil {
		return nil, err
	}
	dec := json.NewDecoder(bytes.NewReader(raw))
	dec.UseNumber()
	var data map[string]any
	if err := dec.Decode(&data); err != nil {
		return nil, fmt.Errorf("skill_stats.json: %w", err)
	}
	out := map[string]skillStats{}
	skills, _ := data["skills"].(map[string]any)
	for name, v := range skills {
		row, ok := v.(map[string]any)
		if !ok {
			continue
		}
		by, _ := row["execution_by_session"].(map[string]any)
		st := skillStats{
			total: num(row["total_executions"]), successes: num(row["successes"]), failures: num(row["failures"]),
			sessions: len(by), streak: num(row["consecutive_failures"]), activations: num(row["activations"]),
		}
		if t, ok := parseISO(row["last_success_at"]); ok {
			st.lastSuccess = &t
		}
		if t, ok := parseISO(row["last_failure_at"]); ok {
			st.lastFailure = &t
		}
		out[name] = st
	}
	return out, nil
}

// parseISO is lifecycle._parse_dt: an ISO-8601 string to UTC; a value with
// no zone is UTC.
func parseISO(v any) (time.Time, bool) {
	s, ok := v.(string)
	if !ok {
		if t, ok := v.(time.Time); ok {
			return t.UTC(), true
		}
		return time.Time{}, false
	}
	s = strings.TrimSpace(s)
	if s == "" {
		return time.Time{}, false
	}
	s = strings.Replace(s, "Z", "+00:00", 1)
	for _, layout := range []string{
		"2006-01-02T15:04:05.999999999-07:00", "2006-01-02T15:04:05.999999999",
		"2006-01-02 15:04:05.999999999-07:00", "2006-01-02 15:04:05.999999999",
		"2006-01-02T15:04-07:00", "2006-01-02T15:04", "2006-01-02",
	} {
		if t, err := time.Parse(layout, s); err == nil {
			return t.UTC(), true
		}
	}
	return time.Time{}, false
}

// pyTruthy is Python's bool() for a decoded YAML value.
func pyTruthy(v any) bool {
	switch t := v.(type) {
	case nil:
		return false
	case bool:
		return t
	case string:
		return t != ""
	case int:
		return t != 0
	case int64:
		return t != 0
	case float64:
		return t != 0
	case []any:
		return len(t) > 0
	case omap:
		return len(t) > 0
	}
	return true
}

func metaFloat(v any) float64 {
	switch t := v.(type) {
	case float64:
		return t
	case int:
		return float64(t)
	case int64:
		return float64(t)
	case bool:
		if t {
			return 1
		}
	case string:
		f, _ := strconv.ParseFloat(strings.TrimSpace(t), 64)
		return f
	}
	return 0
}

// health is lifecycle.SkillHealth.
type health struct {
	name, status               string
	total, successes, failures int64
	sessions                   int
	streak                     int64
	lastSuccess, lastFailure   *time.Time
	autoGenerated              bool
	effort                     float64
	activations                int64
	createdAt, statusChangedAt *time.Time
}

func (h health) successRate() float64 {
	if h.total == 0 {
		return 0
	}
	return float64(h.successes) / float64(h.total)
}

// healthOf is SkillLifecyclePolicy.health_from_stats. dir is the skill folder
// (the SKILL.md mtime stands in for a missing created_at).
func healthOf(s *skill, dir string, st skillStats) health {
	get := func(k string) any { v, _ := s.meta.get(k); return v }
	effort := get("effort_weight")
	if !pyTruthy(effort) {
		effort = get("effort")
	}
	h := health{
		name: s.name, status: s.status,
		total: st.total, successes: st.successes, failures: st.failures,
		sessions: st.sessions, streak: st.streak,
		lastSuccess: st.lastSuccess, lastFailure: st.lastFailure,
		autoGenerated: pyTruthy(get("auto_generated")),
		effort:        metaFloat(effort),
		activations:   st.activations,
	}
	if t, ok := parseISO(get("created_at")); ok {
		h.createdAt = &t
	} else if fi, err := os.Stat(filepath.Join(dir, "SKILL.md")); err == nil {
		t := fi.ModTime().UTC()
		h.createdAt = &t
	}
	if t, ok := parseISO(get("lifecycle_changed_at")); ok {
		h.statusChangedAt = &t
	}
	return h
}

// healthDecision is lifecycle.LifecycleDecision for an existing skill.
type healthDecision struct {
	action, reason, newStatus string
}

func scaled(effort float64, high, medium, base int) int {
	switch {
	case effort >= effortHigh:
		return high
	case effort >= effortMedium:
		return medium
	}
	return base
}

func days(d time.Duration) int { return int(math.Floor(d.Hours() / 24)) }

// evaluateHealth is SkillLifecyclePolicy.evaluate_health with the default
// thresholds: promote, demote, hold or prune on multi-run evidence + effort.
func evaluateHealth(h health, now time.Time) healthDecision {
	name, status, effort := h.name, h.status, h.effort
	ef := fmt.Sprintf("%.2f", effort)
	streakN := scaled(effort, demoteStreak+3, demoteStreak+1, demoteStreak)
	demoteN := scaled(effort, demoteMinExecutions+4, demoteMinExecutions+2, demoteMinExecutions)
	promoteN := promoteMinExecutions
	if effort >= effortHigh {
		promoteN = max(4, promoteMinExecutions-1)
	}
	pruneN := scaled(effort, pruneZeroMinN+5, pruneZeroMinN+2, pruneZeroMinN)
	pruneDays := scaled(effort, pruneDisabledDays*3, pruneDisabledDays*3/2, pruneDisabledDays)
	staleDays := scaled(effort, staleUnusedDays*3, staleUnusedDays*3/2, staleUnusedDays)
	rate := h.successRate()

	if h.streak >= int64(streakN) && (status == "active" || status == "validated" || status == "discovered") {
		return healthDecision{"demote", fmt.Sprintf("%s: %d consecutive failures (threshold %d, effort=%s) — demoting",
			name, h.streak, streakN, ef), "disabled"}
	}
	if h.total >= int64(promoteN) && rate >= promoteMinRate && h.sessions >= promoteMinSessions &&
		h.streak == 0 && status != "active" && status != "deprecated" {
		return healthDecision{"promote", fmt.Sprintf("%s: promote to ACTIVE (n=%d, rate=%s, sessions=%d, effort=%s)",
			name, h.total, pct(rate), h.sessions, ef), "active"}
	}
	probationN := int64(probationMinExec)
	if effort >= effortHigh {
		probationN = 2
	}
	if status == "discovered" && h.total >= probationN && rate >= promoteMinRate && h.successes >= probationN {
		return healthDecision{"promote", fmt.Sprintf("%s: probation passed → VALIDATED (effort=%s)", name, ef), "validated"}
	}
	if h.total >= int64(demoteN) && rate < demoteMaxRate && (status == "active" || status == "validated") {
		return healthDecision{"demote", fmt.Sprintf("%s: demote to DISABLED (n=%d, rate=%s, effort=%s)",
			name, h.total, pct(rate), ef), "disabled"}
	}
	if h.total >= int64(pruneN) && h.successes == 0 {
		return healthDecision{"prune", fmt.Sprintf("%s: %d runs with zero successes — prune (effort=%s)", name, h.total, ef), "deprecated"}
	}
	if h.autoGenerated && h.total == 0 && h.activations == 0 && h.createdAt != nil &&
		(status == "discovered" || status == "validated") {
		age := now.Sub(*h.createdAt)
		if age >= time.Duration(staleDays)*24*time.Hour {
			return healthDecision{"demote", fmt.Sprintf("%s: never used in %dd — demoting (threshold %dd, effort=%s)",
				name, days(age), staleDays, ef), "disabled"}
		}
	}
	anchor := h.lastFailure
	if anchor == nil {
		anchor = h.statusChangedAt
	}
	if status == "disabled" && anchor != nil {
		age := now.Sub(*anchor)
		window := time.Duration(pruneDays) * 24 * time.Hour
		if age >= window && h.successes == 0 {
			return healthDecision{"prune", fmt.Sprintf("%s: disabled and stale (%dd) — prune (effort=%s)", name, days(age), ef), "deprecated"}
		}
		if effort >= effortHigh && h.successes > 0 && age < 2*window {
			return healthDecision{"hold", fmt.Sprintf("%s: hard-won DISABLED held for revive window (%d prior successes, effort=%s)",
				name, h.successes, ef), status}
		}
	}
	return healthDecision{"hold", fmt.Sprintf("%s: keep %s (n=%d, rate=%s, effort=%s)", name, status, h.total, pct(rate), ef), status}
}

// quarantined is a skill the owner quarantined in the Skills panel. The
// Python tick did not look, so good stats could re-promote it; this port
// leaves the owner's decision alone.
func quarantined(s *skill) bool {
	v, _ := s.meta.get("quarantine")
	switch t := v.(type) {
	case bool:
		return t
	case string:
		switch strings.ToLower(strings.TrimSpace(t)) {
		case "true", "yes", "1", "on":
			return true
		}
	}
	return false
}

// learnedSkill is LearningLoop._iter_learned_skills' filter: auto-generated
// or lifecycle-managed, never a library install.
func learnedSkill(s *skill) bool {
	get := func(k string) any { v, _ := s.meta.get(k); return v }
	if scalarText(get("source")) == "library" || pyTruthy(get("library_id")) {
		return false
	}
	switch scalarText(get("trust")) {
	case "imported", "library-install", "library-update":
		return false
	}
	return pyTruthy(get("auto_generated")) || pyTruthy(get("lifecycle"))
}

// TickLearnedSkills is LearningLoop.tick_learned_skills: the unattended
// promote / demote / prune of learned skills under <home>/skills from the
// stats in <home>/skill_stats.json. A changed skill gets its new status,
// lifecycle_last / lifecycle_action / lifecycle_changed_at and the mirrored
// stats (adjust_confidence) written back to its SKILL.md. limit <= 0 is 64.
// It never calls a model.
func TickLearnedSkills(home string, now time.Time, limit int) ([]SkillChange, error) {
	home = expandHome(home)
	if home == "" {
		return nil, nil
	}
	if limit <= 0 {
		limit = tickDefaultLimit
	}
	skillsMu.Lock()
	defer skillsMu.Unlock()
	stats, err := loadSkillStats(home)
	if err != nil {
		return nil, err
	}
	skillsDir := filepath.Join(home, "skills")
	mds, _ := filepath.Glob(filepath.Join(skillsDir, "*", "SKILL.md"))
	sort.Strings(mds)
	var changes []SkillChange
	var errs []error
	seen := map[string]bool{}
	considered := 0
	for _, md := range mds {
		if considered >= limit {
			break
		}
		dir := filepath.Dir(md)
		if seen[filepath.Base(dir)] {
			continue
		}
		s, err := readSkill(dir)
		if err != nil {
			continue // load_skill_from_dir failures are skipped
		}
		name := strings.TrimSpace(s.name)
		if name == "" || seen[name] || !learnedSkill(s) {
			continue
		}
		seen[name] = true
		considered++
		if quarantined(s) {
			continue
		}
		st := stats[name]
		d := evaluateHealth(healthOf(s, dir, st), now)
		if d.action == "hold" || d.action == "reject" || d.newStatus == "" || d.newStatus == s.status {
			continue
		}
		old := s.status
		s.status = d.newStatus
		s.meta.set("lifecycle_last", d.reason)
		s.meta.set("lifecycle_action", d.action)
		s.meta.set("lifecycle_changed_at", isoNow(now))
		// SkillRefiner.adjust_confidence: mirror the stats, never the status.
		s.meta.set("success_rate", st.successRate())
		s.meta.set("total_executions", st.total)
		s.meta.set("stats_sessions", st.sessions)
		if _, err := writeSkill(skillsDir, s); err != nil {
			errs = append(errs, err)
			continue
		}
		changes = append(changes, SkillChange{Name: name, Action: d.action, From: old, To: d.newStatus, Reason: rcut(d.reason, 240)})
	}
	return changes, errors.Join(errs...)
}

package httpapi

// Exports for `remedy skill …` (native/go/cli). The CLI asks the runtime's
// own discovery which skills exist and where, so the CLI and a running
// remedy-runtime agree on what a skill is, where skills live, and which
// copy wins on a name collision.

// CLISkill is one skill as the runtime discovers it.
type CLISkill struct {
	Name          string
	Description   string
	Version       string
	Kind          string
	Status        string // after the runtime's default-status rules
	Dir           string // absolute skill directory
	AutoGenerated bool
	Quarantine    bool
	Tags          []string
}

// CLIDiscoverSkills runs the runtime's skill discovery for home: seed roots
// (bundled / dev checkout / next to the executable), then <home>/skills,
// later names winning. Missing curated skills are seeded into
// <home>/skills exactly as the runtime does on every listing.
func CLIDiscoverSkills(home string) []CLISkill {
	s := &Server{homeDir: home}
	recs := s.discoverSkills()
	out := make([]CLISkill, 0, len(recs))
	for _, r := range recs {
		out = append(out, CLISkill{
			Name: r.Name, Description: r.Description, Version: r.Version, Kind: r.Kind,
			Status: r.Status, Dir: r.Dir, AutoGenerated: r.AutoGenerated, Quarantine: r.Quarantine,
			Tags: append([]string(nil), r.Tags...),
		})
	}
	return out
}

// CLISkillSeedRoots are the curated roots the runtime seeds <home>/skills from.
func CLISkillSeedRoots(home string) []string { return skillSeedRoots(home) }

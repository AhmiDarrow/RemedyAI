func TestRankSkillsOrder(t *testing.T) {
	skills := []skillRecord{
		// tests/test_partner_memory.py::test_skill_rank_prefers_lower_cost
		{Name: "slow-skill", Description: "recover git commits", Status: "active", Meta: map[string]string{"avg_duration_ms": "120000", "success_rate": "0.9"}},
		{Name: "fast-skill", Description: "recover git commits", Status: "active", Meta: map[string]string{"avg_duration_ms": "800", "success_rate": "0.9"}},
		{Name: "file-read-list-dir-bash-exec", Description: "recover git commits", Status: "discovered", AutoGenerated: true},
		{Name: "bevy", Description: "Build Rust games", Status: "active", Triggers: []string{`\bbevy\b`}},
		{Name: "git-vault", Description: "recover git commits", Status: "active", Quarantine: true},
		{Name: "git-old", Description: "recover git commits", Status: "disabled"},
	}
	names := func(r []rankedSkill) []string {
		var out []string
		for _, x := range r {
			out = append(out, x.rec.Name)
		}
		return out
	}
	got := names(rankSkills(skills, "recover git commits", 10, ""))
	want := []string{"fast-skill", "slow-skill", "file-read-list-dir-bash-exec", "bevy"}
	if strings.Join(got, ",") != strings.Join(want, ",") {
		t.Fatalf("rank=%v want %v", got, want)
	}
	// A trigger hit lifts a domain pack; quarantine shows only when named.
	if got := names(rankSkills(skills, "make a bevy game", 1, "")); got[0] != "bevy" {
		t.Fatalf("trigger rank=%v", got)
	}
	if got := names(rankSkills(skills, "use git-vault to recover git commits", 10, "")); !strings.Contains(strings.Join(got, ","), "git-vault") {
		t.Fatalf("named quarantine missing: %v", got)
	}
	if got := rankSkills(skills, "recover", 2, ""); len(got) != 2 {
		t.Fatalf("limit ignored: %d", len(got))
	}
	if !looksLikeToolChainSkillName("file-read-list-dir-bash-exec") || looksLikeToolChainSkillName("git-recover") {
		t.Fatal("tool-chain name detection")
	}
}

func writeSkill(t *testing.T, home, name, front, body string) string {
	t.Helper()
	dir := filepath.Join(home, "skills", name)
	if err := os.MkdirAll(filepath.Join(dir, "references"), 0o700); err != nil {
		t.Fatal(err)
	}
	md := "---\nname: " + name + "\ndescription: fixture " + name + "\n" + front + "---\n" + body + "\n"
	if err := os.WriteFile(filepath.Join(dir, "SKILL.md"), []byte(md), 0o600); err != nil {
		t.Fatal(err)
	}
	return dir
}

func TestSkillToolsActivateAndSearch(t *testing.T) {
	e := newMemToolEnv(t)
	home := e.s.skillsHome()
	dir := writeSkill(t, home, "zz-fixture-ok", "tags:\n  - zzfix\n  - shared\ntools: [file_read]\ntriggers:\n  - \"\\\\bzzfixture\\\\b\"\n", "Do the fixture thing.")
	_ = os.WriteFile(filepath.Join(dir, "references", "INDEX.md"), []byte("index body"), 0o600)
	_ = os.WriteFile(filepath.Join(dir, "references", "b.md"), []byte("b body"), 0o600)
	writeSkill(t, home, "zz-fixture-sibling", "tags: [shared]\n", "Sibling.")
	writeSkill(t, home, "zz-fixture-quarantined", "quarantine: true\n", "Untrusted.")
	writeSkill(t, home, "zz-fixture-disabled", "status: disabled\n", "Off.")

	out, err := e.call(t, "skill.activate", map[string]any{"name": "zz-fixture-ok", "include_references": true})
	if err != nil {
		t.Fatal(err)
	}
	body := asString(out["body"])
	for _, want := range []string{"# Skill: zz-fixture-ok", "**Status:** active", "**Tags:** zzfix, shared", "**Tools:** file_read",
		"Do the fixture thing.", "## References (on disk)", "## Reference: references/INDEX.md\n\nindex body"} {
		if !strings.Contains(body, want) {
			t.Fatalf("body missing %q:\n%s", want, body)
		}
	}
	if strings.Index(body, "references/INDEX.md (") > strings.Index(body, "references/b.md (") {
		t.Fatal("INDEX.md must be listed first")
	}
	if int(out["chars"].(float64)) != len([]rune(body)) || out["name"] != "zz-fixture-ok" {
		t.Fatalf("activate out: %#v", out)
	}
	if rel, _ := out["related"].([]any); len(rel) == 0 || rel[0] != "zz-fixture-sibling" {
		t.Fatalf("related=%v", out["related"])
	}

	for name, want := range map[string]string{
		"zz-fixture-quarantined": "skill 'zz-fixture-quarantined' is quarantined; Trust it in the Skills panel first",
		"zz-fixture-disabled":    "skill 'zz-fixture-disabled' is disabled (not active)",
		"all skills":             "refusing bulk skill.activate; load one pack per task (use skill.search then skill.activate with an exact name)",
		"reload_all":             "refusing bulk skill.activate; load one pack per task (use skill.search then skill.activate with an exact name)",
	} {
		if _, err := e.call(t, "skill.activate", map[string]any{"name": name}); err == nil || err.Error() != want {
			t.Errorf("activate(%q) err=%v want %q", name, err, want)
		}
	}
	if _, err := e.call(t, "skill.activate", map[string]any{"name": "zz-no-such-skill"}); err == nil ||
		!strings.HasPrefix(err.Error(), "skill not found: zz-no-such-skill; closest: ") {
		t.Fatalf("unknown skill err=%v", err)
	}

	out, err = e.call(t, "skill.search", map[string]any{"query": "zzfixture zz fixture ok", "limit": 3})
	if err != nil {
		t.Fatal(err)
	}
	skills := out["skills"].([]any)
	top := skills[0].(map[string]any)
	if top["name"] != "zz-fixture-ok" || top["status"] != "active" || int(out["total"].(float64)) != len(skills) || len(skills) > 3 {
		t.Fatalf("search: %#v", out)
	}
	for _, s := range skills {
		if n := asString(s.(map[string]any)["name"]); n == "zz-fixture-quarantined" || n == "zz-fixture-disabled" {
			t.Fatalf("search returned %s", n)
		}
	}
}

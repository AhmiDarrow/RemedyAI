// Every test runs against a t.TempDir() home and never the owner's ~/.remedy:
// REMEDY_HOME and HOME are pointed at temp dirs, the project seed is faked,
// and no test reaches the network or opens a browser.

type cfgRun struct {
	code     int
	out, err string
}

func cfgTestHome(t *testing.T) string {
	t.Helper()
	home := filepath.Join(t.TempDir(), "home")
	if err := os.MkdirAll(home, 0o700); err != nil {
		t.Fatal(err)
	}
	t.Setenv("REMEDY_HOME", home)
	t.Setenv("HOME", t.TempDir())
	t.Setenv("USERPROFILE", t.TempDir())
	for _, k := range []string{
		"XAI_API_KEY", "REMEDY_XAI_API_KEY", "OPENAI_API_KEY", "REMEDY_LLM_API_KEY",
		"ANTHROPIC_API_KEY", "GROQ_API_KEY", "REMEDY_CLI_VERSION",
	} {
		t.Setenv(k, "")
		os.Unsetenv(k)
	}
	seed := filepath.Join(t.TempDir(), "seed-project")
	if err := os.MkdirAll(seed, 0o755); err != nil {
		t.Fatal(err)
	}
	prevSeed := cfgProjectSeed
	cfgProjectSeed = func() (string, error) { return seed, nil }
	t.Cleanup(func() { cfgProjectSeed = prevSeed })
	httpapi.InvalidateConfigCache()
	return home
}

func cfgCLI(t *testing.T, home, stdin string, args ...string) cfgRun {
	t.Helper()
	var out, errw bytes.Buffer
	argv := append([]string{"--home", home}, args...)
	code := Run(argv, &out, &errw, strings.NewReader(stdin), Hooks{}, "test")
	return cfgRun{code, out.String(), errw.String()}
}

func cfgReadFile(t *testing.T, path string) string {
	t.Helper()
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(raw)
}

func cfgWrite(t *testing.T, path, text string) {
	t.Helper()
	if err := os.WriteFile(path, []byte(text), 0o600); err != nil {
		t.Fatal(err)
	}
	httpapi.InvalidateConfigCache()
}


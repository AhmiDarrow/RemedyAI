def pack(code: str, sec: tuple[str, ...], extra: tuple[str, ...]) -> None:
    if len(sec) != len(_SEC_ORDER):
        raise ValueError(f"{code} sec {len(sec)} != {len(_SEC_ORDER)}")
    if len(extra) != len(_EXTRA_ORDER):
        raise ValueError(f"{code} extra {len(extra)} != {len(_EXTRA_ORDER)}")
    kw = dict(zip(_SEC_ORDER, sec, strict=True))
    _f(code, _sec(**kw, extra=dict(zip(_EXTRA_ORDER, extra, strict=True))))


